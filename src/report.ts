  page.drawLine({ start: { x: 48, y: 704 }, end: { x: 564, y: 704 }, thickness: 1, color: border })

  page.drawText('EXECUTIVE BRIEF  #37', { x: 48, y: 674, size: 8, font: bold, color: teal })
  page.drawText('A week of strong growth,', { x: 48, y: 633, size: 25, font: bold, color: navy })
